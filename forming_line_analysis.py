"""Production data analysis of an assumed forming line: downtime, scrap, OEE and material balance.

SELF INITIATED STUDY. EVERY INPUT BELOW IS ASSUMED. The shift records are generated by this script.
Run:  python forming_line_analysis.py      (needs numpy, pandas, matplotlib, openpyxl)
Outputs: report.xlsx, downtime_pareto.png, weekly_oee.png, results.json
"""
import json
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

SEED = 2026
PRESSES = ["P1", "P2", "P3"]
WEEKS, DAYS, SHIFTS = 4, 5, 3
PLANNED_MIN = 480                      # assumed minutes per shift
IDEAL_CYCLE_S, CAVITIES = 20.0, 16     # assumed ideal press cycle and cavities
PART_G = 0.9                           # assumed part mass in grams
PROCESS_LOSS = 0.035                   # assumed runner and purge loss as share of input material
DOWNTIME = {                           # assumed cause: (events per shift, mean minutes, sd minutes)
    "Tool change": (0.9, 22, 6), "Material shortage": (0.35, 35, 10),
    "Maintenance": (0.2, 45, 12), "Quality hold": (0.3, 18, 5)}
SCRAP = {"Flash": 0.012, "Short shot": 0.008, "Contamination": 0.005}   # assumed mean scrap share of parts


def generate(rng):
    rows = []
    for p in PRESSES:
        for w in range(1, WEEKS + 1):
            for d in range(DAYS):
                for s in range(SHIFTS):
                    rec = dict(press=p, week=w, day=d + 1, shift=s + 1)
                    lost = 0.0
                    for cause, (lam, mu, sd) in DOWNTIME.items():
                        n = rng.poisson(lam)
                        m = float(np.clip(rng.normal(mu, sd, n), 3, None).sum()) if n else 0.0
                        rec["down_" + cause] = m
                        lost += m
                    run = max(PLANNED_MIN - lost, 0.0)
                    cycle = IDEAL_CYCLE_S * (1 + max(rng.normal(0.06, 0.03), 0.0))
                    parts = run * 60.0 / cycle * CAVITIES
                    rec.update(planned_min=PLANNED_MIN, run_min=run, cycle_s=cycle, parts=parts)
                    scrap_total = 0.0
                    for cause, base in SCRAP.items():
                        k = parts * base * rng.lognormal(0.0, 0.35)
                        rec["scrap_" + cause] = k
                        scrap_total += k
                    rec["scrap_parts"] = scrap_total
                    rows.append(rec)
    return pd.DataFrame(rows)


def analyse(df):
    df = df.copy()
    df["good_parts"] = df["parts"] - df["scrap_parts"]
    A = df["run_min"].sum() / df["planned_min"].sum()
    ideal_parts = df["run_min"].sum() * 60.0 * CAVITIES / IDEAL_CYCLE_S   # parts at the ideal cycle time
    P = df["parts"].sum() / ideal_parts
    Q = df["good_parts"].sum() / df["parts"].sum()
    out = dict(shifts=len(df), availability=round(100 * A, 1), performance=round(100 * P, 1),
               quality=round(100 * Q, 1), OEE=round(100 * A * P * Q, 1))
    down = pd.Series({c: df["down_" + c].sum() for c in DOWNTIME}).sort_values(ascending=False)
    out["downtime_share_percent"] = (100 * down / down.sum()).round(1).to_dict()
    out["downtime_hours_total"] = round(down.sum() / 60.0, 1)
    scr = pd.Series({c: df["scrap_" + c].sum() for c in SCRAP}).sort_values(ascending=False)
    out["scrap_share_percent"] = (100 * scr / scr.sum()).round(1).to_dict()
    out["scrap_rate_percent"] = round(100 * scr.sum() / df["parts"].sum(), 2)
    good_kg = df["good_parts"].sum() * PART_G / 1000.0
    scrap_kg = scr.sum() * PART_G / 1000.0
    input_kg = (good_kg + scrap_kg) / (1 - PROCESS_LOSS)
    out["material_balance_kg"] = dict(input=round(input_kg), good=round(good_kg), scrap=round(scrap_kg),
                                      runner_and_purge_loss=round(input_kg - good_kg - scrap_kg))
    out["material_yield_percent"] = round(100 * good_kg / input_kg, 1)
    wk = {}
    for w, g in df.groupby("week"):
        a = g["run_min"].sum() / g["planned_min"].sum()
        pf = g["parts"].sum() / (g["run_min"].sum() * 60.0 * CAVITIES / IDEAL_CYCLE_S)
        q = g["good_parts"].sum() / g["parts"].sum()
        wk[int(w)] = round(100 * a * pf * q, 1)
    out["weekly_OEE"] = wk
    pr = {p: round(100 * (g["run_min"].sum() / g["planned_min"].sum()) *
                   (g["parts"].sum() / (g["run_min"].sum() * 60.0 * CAVITIES / IDEAL_CYCLE_S)) *
                   (g["good_parts"].sum() / g["parts"].sum()), 1) for p, g in df.groupby("press")}
    out["press_OEE"] = pr
    return df, down, scr, out


def main():
    rng = np.random.default_rng(SEED)
    df = generate(rng)
    df, down, scr, res = analyse(df)
    json.dump(res, open("results.json", "w"), indent=2)
    fig, ax = plt.subplots(figsize=(6.5, 3.4))
    ax.bar(down.index, down.values / 60.0)
    ax2 = ax.twinx(); ax2.plot(down.index, 100 * down.cumsum() / down.sum(), "k-o"); ax2.set_ylim(0, 105)
    ax.set_ylabel("Downtime hours (assumed data)"); ax2.set_ylabel("Cumulative %")
    fig.tight_layout(); fig.savefig("downtime_pareto.png", dpi=150)
    fig, ax = plt.subplots(figsize=(6.5, 3.2))
    ax.plot(list(res["weekly_OEE"].keys()), list(res["weekly_OEE"].values()), "-o")
    ax.set_xlabel("Week"); ax.set_ylabel("OEE in % (assumed data)"); ax.set_xticks(list(res["weekly_OEE"].keys()))
    fig.tight_layout(); fig.savefig("weekly_oee.png", dpi=150)
    with pd.ExcelWriter("report.xlsx") as xw:
        pd.DataFrame([{k: v for k, v in res.items() if not isinstance(v, dict)}]).T.to_excel(xw, sheet_name="Summary", header=False)
        df.round(2).to_excel(xw, sheet_name="ShiftData", index=False)
        down.rename("minutes").to_frame().to_excel(xw, sheet_name="DowntimePareto")
        scr.rename("parts").round(0).to_frame().to_excel(xw, sheet_name="ScrapCauses")
        pd.Series(res["material_balance_kg"], name="kg").to_frame().to_excel(xw, sheet_name="MaterialBalance")
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
